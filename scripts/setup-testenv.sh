#!/usr/bin/env bash
# ┌─────────────────────────────────────────────────────────────────────────┐
# │  appenv UX Test Environment Setup                                       │
# │                                                                         │
# │  Creates 16 scenarios across 4 tester personas for CLI UX evaluation.  │
# │                                                                         │
# │  Personas:                                                              │
# │    Anna   — Fresh user, first encounter with appenv                     │
# │    Bernd  — Dependency manager, version constraints & conflicts         │
# │    Claudia— Ops/production, broken states & recovery                    │
# │    Dieter — Migration from old appenv (requirements.txt + pip)          │
# │                                                                         │
# │  Usage:                                                                 │
# │    bash /appenv/scripts/setup-testenv.sh                                │
# │                                                                         │
# │  Test environments are created under:                                   │
# │    /appenv/tmp/appenv/<persona>/<scenario>/                             │
# │                                                                         │
# │  Each round starts fresh (rm -rf + rebuild).                            │
# └─────────────────────────────────────────────────────────────────────────┘
set -euo pipefail

# ── Environment ──────────────────────────────────────────────────────────
# Strip agent interceptors from PATH, ensure uv is available
export PATH="/srv/s-dev/.nix-profile/bin:$(
    echo "$PATH" \
        | tr ':' '\n' \
        | grep -v '/.agents/interceptors/' \
        | tr '\n' ':'
)"

BASE="/appenv/tmp/appenv"
APPENV_SRC="/appenv/src/appenv.py"

# ── Colors ───────────────────────────────────────────────────────────────
RED='\033[0;31m'
GREEN='\033[0;32m'
YELLOW='\033[0;33m'
BLUE='\033[0;34m'
CYAN='\033[0;36m'
BOLD='\033[1m'
NC='\033[0m'

# ── Helpers ──────────────────────────────────────────────────────────────

header() {
    echo ""
    echo -e "${BOLD}${BLUE}━━━ $1 ━━━${NC}"
    echo ""
}

info() {
    echo -e "  ${CYAN}▸${NC} $1"
}

ok() {
    echo -e "  ${GREEN}✓${NC} $1"
}

warn() {
    echo -e "  ${YELLOW}⚠${NC} $1"
}

fail() {
    echo -e "  ${RED}✗${NC} $1"
}

separator() {
    echo ""
    echo -e "  ${BLUE}─────────────────────────────────────────${NC}"
    echo ""
}

# ── Core Setup Functions ─────────────────────────────────────────────────

cleanup() {
    echo -e "${BOLD}${RED}🧹  Cleaning up ${BASE} ...${NC}"
    rm -rf "$BASE"
    mkdir -p "$BASE"
}

copy_appenv() {
    local dir="$1"
    cp "$APPENV_SRC" "$dir/appenv"
    chmod +x "$dir/appenv"
}

# Write a minimal pyproject.toml with optional dependencies
write_pyproject() {
    local dir="$1"
    local name="$2"
    shift 2

    cat > "$dir/pyproject.toml" <<HEADER
[project]
name = "${name}"
version = "0.1.0"
requires-python = ">=3.10"
HEADER

    if [[ $# -gt 0 ]]; then
        echo "dependencies = [" >> "$dir/pyproject.toml"
        for dep in "$@"; do
            echo "    \"${dep}\"," >> "$dir/pyproject.toml"
        done
        echo "]" >> "$dir/pyproject.toml"
    fi
    echo "" >> "$dir/pyproject.toml"
}

# Bootstrap a full venv: create lockfile then prepare
# Uses python3 directly since /usr/bin/env may not exist (NixOS)
bootstrap_venv() {
    local dir="$1"
    (cd "$dir" && python3 ./appenv update-lockfile 2>&1 && python3 ./appenv prepare 2>&1) || {
        fail "bootstrap_venv failed in $dir"
        return 1
    }
}

# Create a binary symlink pointing to appenv
make_symlink() {
    local dir="$1"
    local name="$2"
    ln -sf appenv "$dir/$name"
}

# Create old-style appenv directory structure (legacy hash-based venv)
create_old_appenv() {
    local dir="$1"
    local hash="${2:-abc123def456}"

    mkdir -p "$dir/.appenv/${hash}/bin"
    mkdir -p "$dir/.appenv/${hash}/lib"

    # Fake pyvenv.cfg
    cat > "$dir/.appenv/${hash}/pyvenv.cfg" <<CFG
home = /usr/bin
include-system-site-packages = false
version = 3.11.9
CFG

    # Fake python binary
    cat > "$dir/.appenv/${hash}/bin/python" <<'SCRIPT'
#!/bin/sh
echo "Python 3.11.9 (old appenv)"
SCRIPT
    chmod +x "$dir/.appenv/${hash}/bin/python"

    # .appenv/current symlink -> hash dir
    ln -sf "$hash" "$dir/.appenv/current"
}

# Write a requirements.txt
write_requirements() {
    local dir="$1"
    shift
    cat > "$dir/requirements.txt" <<REQ
# This file is autogenerated by pip-compile with Python 3.11
# To update, run: pip-compile requirements.in
REQ
    for dep in "$@"; do
        echo "$dep" >> "$dir/requirements.txt"
    done
}

# Write a requirements.lock (old appenv internal lockfile)
write_requirements_lock() {
    local dir="$1"
    shift
    cat > "$dir/requirements.lock" <<HEADER
# Lockfile generated by old appenv
# Format: package==version
HEADER
    for dep in "$@"; do
        echo "$dep" >> "$dir/requirements.lock"
    done
}


# ══════════════════════════════════════════════════════════════════════════
#  ANNA — Fresh User
# ══════════════════════════════════════════════════════════════════════════
#
#  Anna has never used appenv. She's bootstrapping a new project from
#  scratch. She needs to understand init, prepare, adding deps, and
#  running binaries via symlinks.
#
#  Scenarios:
#    01-fresh      — Empty directory, just appenv copied in
#    02-prepared   — Fully bootstrapped with httpie, http symlink
#    03-with-tests — src-layout with dev deps in dependency-groups
# ─────────────────────────────────────────────────────────────────────────

setup_anna() {
    header "ANNA — Fresh User (3 scenarios)"

    # ── 01-fresh ────────────────────────────────────────────
    local dir="$BASE/anna/01-fresh"
    info "01-fresh: Empty directory for interactive init"
    mkdir -p "$dir"
    copy_appenv "$dir"
    ok "Ready: empty dir + appenv binary"

    separator

    # ── 02-prepared ─────────────────────────────────────────
    dir="$BASE/anna/02-prepared"
    info "02-prepared: Bootstrapped with httpie + http symlink"
    mkdir -p "$dir"
    copy_appenv "$dir"
    write_pyproject "$dir" "anna-app" "httpie>=3.2"
    bootstrap_venv "$dir"
    make_symlink "$dir" "http"
    ok "Ready: pyproject.toml + venv + lock + http symlink"

    separator

    # ── 03-with-tests ───────────────────────────────────────
    dir="$BASE/anna/03-with-tests"
    info "03-with-tests: src-layout with dev deps"
    mkdir -p "$dir/src/myapp" "$dir/tests"
    copy_appenv "$dir"

    cat > "$dir/pyproject.toml" <<'TOML'
[project]
name = "myapp"
version = "0.1.0"
requires-python = ">=3.10"
dependencies = [
    "requests>=2.31",
]

[dependency-groups]
dev = [
    "pytest>=8.0",
    "ruff>=0.4",
]
TOML

    # src/myapp/__init__.py
    cat > "$dir/src/myapp/__init__.py" <<'PY'
"""My application package."""

__version__ = "0.1.0"
PY

    # src/myapp/core.py
    cat > "$dir/src/myapp/core.py" <<'PY'
"""Core application logic."""


def greet(name: str) -> str:
    """Return a greeting."""
    return f"Hello, {name}!"


def fetch_url(url: str) -> dict:
    """Fetch a URL and return status info. Requires requests."""
    import requests

    resp = requests.get(url, timeout=10)
    return {"status": resp.status_code, "url": url}
PY

    # tests/test_basic.py
    cat > "$dir/tests/test_basic.py" <<'PY'
"""Basic tests for myapp."""

from myapp.core import greet


def test_greet():
    assert greet("World") == "Hello, World!"


def test_greet_empty():
    assert greet("") == "Hello, !"
PY

    bootstrap_venv "$dir"
    ok "Ready: src-layout + tests + dev deps in dependency-groups"
}


